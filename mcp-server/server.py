@shop.tool(model=True)
def get_purchase_journey_summary(journey_id: str, merchant_id: str = "STRIDEHUB") -> dict:
    """Read the saved Mandate Lens journey and explain its latest result.

    Call this when a shopper or merchant asks what happened, why an action was blocked,
    or why a purchase failed, and they provide a journey ID. This is read-only: it does not
    change a cart, re-run Guard, retry a payment, or create a new journey. Report the returned
    explanation, cause, and next step. Do not guess when the stored journey lacks a cause.
    """
    if not journey_id or not journey_id.strip():
        return {"ok": False, "message": "Please provide the journey ID from the Merchant order or Pulse history."}
    if not merchant_id or not merchant_id.strip():
        return {"ok": False, "message": "A merchant ID is required to look up the journey."}
    logger.info("Journey summary lookup started journeyId=%s merchantId=%s", journey_id.strip(), merchant_id.strip())
    query = urlencode({"merchantId": merchant_id.strip()})
    path = f"/api/v1/journeys/{quote(journey_id.strip(), safe='')}?{query}"
    try:
        journey = mandate_lens_request(path)
    except RuntimeError as error:
        logger.exception("Journey summary lookup failed journeyId=%s merchantId=%s",
                         journey_id.strip(), merchant_id.strip())
        return {"ok": False, "journeyId": journey_id, "message": str(error)}
    operations = [{key: operation.get(key) for key in (
        "operationId", "cartId", "action", "status", "decisionId", "resultEventId", "createdAt", "resolvedAt"
    )} for operation in journey.get("operations", [])]
    decisions = [{key: decision.get(key) for key in (
        "decisionId", "operationId", "action", "decision", "reasons", "ruleResults", "evaluatedAt"
    )} for decision in journey.get("decisions", [])]
    event_detail_fields = (
        "operationId", "action", "cartId", "summary", "errorMessage", "failureCode", "message",
        "total", "currency", "resultDetails",
    )
    timeline = [{
        key: event.get(key) for key in (
            "eventId", "type", "source", "outcome", "correlationId", "occurredAt"
        )
    } | {"details": {key: event.get("details", {}).get(key) for key in event_detail_fields
                      if key in (event.get("details") or {})}}
        for event in journey.get("timeline", [])]
    logger.info("Journey summary lookup completed journeyId=%s status=%s operations=%s decisions=%s timelineEvents=%s latestEvent=%s latestOutcome=%s",
                journey.get("journeyId"), journey.get("status"), len(operations), len(decisions),
                len(timeline), journey.get("latestEventType"), journey.get("latestOutcome"))
    return {
        "ok": True,
        "journeyId": journey.get("journeyId"),
        "merchantId": journey.get("merchantId"),
        "cartId": journey.get("cartId"),
        "status": journey.get("status"),
        "explanation": journey.get("explanation"),
        "latestEventType": journey.get("latestEventType"),
        "latestOutcome": journey.get("latestOutcome"),
        "operations": operations,
        "decisions": decisions,
        "timeline": timeline,
        "message": "This is a read-only explanation built from saved journey records. No cart or payment action was performed.",
    }


def current_cart(session_id: str | None = None) -> dict:
    session_id = session_id or ACTIVE_SESSION_ID
    session = SESSIONS.get(session_id) if session_id else None
    active_cart = CARTS.get(session_id) if session_id else None
    if not active_cart:
        return {"items": [], "total": 0, "currency": "USD",
                "budget": session.get("maxAmount") if session and not session.get("completed") else None,
                "status": "COMPLETED" if session and session.get("completed") else "EMPTY"}

    products_by_id = {product.get("id"): product for product in PRODUCTS}
    lines = []
    for item in active_cart.get("items", []):
        product = products_by_id.get(item.get("variant_id"), {})
        line_total = float((item.get("item_total") or {}).get("value") or 0)
        lines.append({**product, "id": item.get("variant_id"),
                      "name": item.get("name") or product.get("name", "Footwear item"),
                      "quantity": item.get("quantity", 0), "line_total": line_total})
    total = float(((active_cart.get("totals") or {}).get("total") or {}).get("value") or 0)
    return {"items": lines, "total": total,
            "currency": ((active_cart.get("totals") or {}).get("total") or {}).get("currency_code", "USD"),
            "budget": session.get("maxAmount") if session and not session.get("completed") else None,
            "status": "COMPLETED" if session and session.get("completed")
            else active_cart.get("status", "ACTIVE")}


def resolve_session(session_id: str | None = None, allow_completed: bool = False) -> tuple[str, dict]:
    resolved_id = session_id or ACTIVE_SESSION_ID
    session = SESSIONS.get(resolved_id) if resolved_id else None
    if not session:
        raise RuntimeError("No shopping session is active. Browsing is available now; before adding items, ask the shopper for a budget and start a shopping session.")
    if session.get("completed") and not allow_completed:
        raise RuntimeError("This shopping journey is complete and its cart is read-only. Start a new shopping session before adding items again.")
    return resolved_id, session


def merchant_request(method: str, path: str, payload: dict | None = None) -> dict:
    body = json.dumps(payload).encode("utf-8") if payload is not None else None
    request = Request(f"{MERCHANT_API_BASE_URL}{path}", data=body, method=method,
                      headers={"Accept": "application/json", "Content-Type": "application/json"})
    started = time.perf_counter()
    logger.info("Merchant HTTP request started method=%s path=%s payloadBytes=%s",
                method, path, len(body) if body is not None else 0)
    try:
        with urlopen(request, timeout=10) as response:
            response_body = response.read()
            result = json.loads(response_body.decode("utf-8"))
            logger.info("Merchant HTTP request completed method=%s path=%s status=%s durationMs=%.1f responseBytes=%s responseKeys=%s",
                        method, path, response.status, (time.perf_counter() - started) * 1000,
                        len(response_body), sorted(result.keys()) if isinstance(result, dict) else type(result).__name__)
            return result
    except HTTPError as error:
        detail = error.read().decode("utf-8", errors="replace")
        logger.warning("Merchant HTTP request failed method=%s path=%s status=%s durationMs=%.1f responseBytes=%s",
                       method, path, error.code, (time.perf_counter() - started) * 1000, len(detail))
        try:
            problem = json.loads(detail)
            detail = problem.get("detail") or problem.get("message") or detail
        except json.JSONDecodeError:
            pass
        raise RuntimeError(f"Merchant API returned HTTP {error.code}: {detail}") from error
    except (URLError, TimeoutError, json.JSONDecodeError) as error:
        logger.exception("Merchant HTTP request errored method=%s path=%s durationMs=%.1f errorType=%s",
                         method, path, (time.perf_counter() - started) * 1000, type(error).__name__)
        raise RuntimeError(
            f"Could not reach Merchant API at {MERCHANT_API_BASE_URL}. Start the merchant API and try again."
        ) from error


