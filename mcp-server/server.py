def apply_items_to_demo_cart(items: list[dict], session_id: str) -> dict:
    """Submit one complete proposed cart so Guard evaluates the combined set atomically."""
    global PRODUCTS
    try:
        session_id, session = resolve_session(session_id)
    except RuntimeError as error:
        logger.warning("Cart mutation rejected sessionId=%s reason=%s", session_id, error)
        return {"ok": False, "cartMessage": str(error), "message": str(error)}
    active_cart = CARTS.get(session_id)
    logger.info("Cart mutation started sessionId=%s journeyId=%s cartId=%s itemCount=%s currentTotal=%s proposedItems=%s budget=%s",
                session_id, session.get("journeyId"), (active_cart or {}).get("id"),
                len(items), current_cart(session_id).get("total"),
                [{"productId": item.get("product_id"), "quantity": item.get("quantity")} for item in items],
                session.get("maxAmount"))
    try:
        PRODUCTS = fetch_footwear_products()
    except RuntimeError as error:
        logger.exception("Cart mutation failed while loading catalog sessionId=%s journeyId=%s",
                         session_id, session.get("journeyId"))
        return {"message": str(error), "cartMessage": str(error), "ok": False,
                "checkoutChecked": False, "checkoutOperationId": None, "operationId": None,
                "checkoutError": None, "guardResult": None, "cart": current_cart(session_id)}
    product_by_id = {str(product.get("id")): product for product in PRODUCTS}
    current_items = {str(item.get("variant_id")): int(item.get("quantity", 0))
                     for item in (active_cart or {}).get("items", [])}
    names = []
    for proposed in items:
        product_id = str(proposed.get("product_id", ""))
        quantity = proposed.get("quantity", 0)
        if type(quantity) is not int or quantity < 1 or quantity > 20:
            message = "Quantity must be a whole number from 1 to 20."
            logger.warning("Cart mutation rejected sessionId=%s reason=INVALID_QUANTITY productId=%s quantity=%s",
                           session_id, product_id, quantity)
            return {"ok": False, "decision": "BLOCK", "message": message, "cartMessage": message,
                    "checkoutChecked": False, "checkoutOperationId": None, "operationId": None,
                    "checkoutError": None, "guardResult": None, "cart": current_cart(session_id)}
        product = product_by_id.get(product_id)
        if not product:
            message = f"Product {product_id} was not found."
            logger.warning("Cart mutation rejected sessionId=%s reason=PRODUCT_NOT_FOUND productId=%s",
                           session_id, product_id)
            return {"ok": False, "decision": "BLOCK", "message": message, "cartMessage": message,
                    "checkoutChecked": False, "checkoutOperationId": None, "operationId": None,
                    "checkoutError": None, "guardResult": None, "cart": current_cart(session_id)}
        current_items[product_id] = current_items.get(product_id, 0) + quantity
        names.append({"productId": product_id, "name": product.get("name", "Footwear item"),
                      "quantity": quantity})

    payload = cart_request_body([{"variant_id": item_id, "quantity": item_quantity}
                                 for item_id, item_quantity in current_items.items()],
                                session if not active_cart else None)
    try:
        if active_cart and active_cart.get("id"):
            logger.info("Cart mutation submitting method=PUT cartId=%s journeyId=%s uniqueProducts=%s",
                        active_cart["id"], session.get("journeyId"), len(current_items))
            updated = merchant_request("PUT", f"/merchant-cart/{active_cart['id']}", payload)
        else:
            logger.info("Cart mutation submitting method=POST journeyId=%s uniqueProducts=%s",
                        session.get("journeyId"), len(current_items))
            updated = merchant_request("POST", "/merchant-cart", payload)
    except RuntimeError as error:
        logger.exception("Cart mutation request failed sessionId=%s journeyId=%s cartId=%s proposedProductCount=%s",
                         session_id, session.get("journeyId"), (active_cart or {}).get("id"), len(current_items))
        return {"ok": False, "decision": "BLOCK" if "HTTP 409" in str(error) else None,
                "cartMessage": f"Cart change was not saved: {error}", "cart": current_cart(session_id),
                "checkoutChecked": False, "checkoutOperationId": None, "operationId": None,
                "checkoutError": None, "guardResult": None}
    CARTS[session_id] = updated
    logger.info("Cart mutation accepted sessionId=%s journeyId=%s cartId=%s itemCount=%s total=%s currency=%s status=%s",
                session_id, session.get("journeyId"), updated.get("id"),
                len(updated.get("items", [])), current_cart(session_id).get("total"),
                current_cart(session_id).get("currency"), updated.get("status"))
    return {"ok": True, "decision": "ALLOW", "addedItems": names,
            "cartMessage": "Merchant saved the complete proposed cart after Guard allowed the item change.",
            "checkoutChecked": False, "checkoutOperationId": None, "operationId": None,
            "checkoutError": None, "guardResult": None,
            "cart": current_cart(session_id)}


