def product_image_source(product: dict, index: int) -> str:
    """Inline catalog images for MCP App CSP; always return a renderable fallback."""
    image_url = product.get("imageUrl")
    if isinstance(image_url, str) and image_url not in IMAGE_CACHE:
        parsed = urlparse(image_url)
        if parsed.scheme == "https" and parsed.hostname == "images.unsplash.com":
            query = dict(item.split("=", 1) for item in parsed.query.split("&") if "=" in item)
            query.update({"fit": "crop", "w": "640", "q": "72", "fm": "jpg"})
            url = parsed._replace(query=urlencode(query)).geturl()
            request = Request(url, headers={"Accept": "image/jpeg", "User-Agent": "MandateLensDemo/1.0"})
            try:
                with urlopen(request, timeout=4) as response:
                    content_type = response.headers.get_content_type()
                    image_bytes = response.read(1_000_001)
                if content_type.startswith("image/") and len(image_bytes) <= 1_000_000:
                    encoded = base64.b64encode(image_bytes).decode("ascii")
                    IMAGE_CACHE[image_url] = f"data:{content_type};base64,{encoded}"
            except (HTTPError, URLError, TimeoutError, OSError):
                pass

    if isinstance(image_url, str) and image_url in IMAGE_CACHE:
        return IMAGE_CACHE[image_url]
    return shoe_art(("#db503f", "#bd3c36", "#c987a1")[index % 3])


def preload_product_images(products: list[dict]) -> list[str]:
    if not products:
        return []
    with ThreadPoolExecutor(max_workers=min(8, len(products))) as executor:
        return list(executor.map(
            lambda item: product_image_source(item[1], item[0]),
            enumerate(products),
        ))


@shop.tool()
def prepare_purchase_item(max_amount: float, query: str = "", quantity: int = 1,
                          product_id: str = "", cart_id: str = "", different_models: int = 1) -> dict:
    """Search Merchant only after the shopper submits a budget in the purchase UI."""
    if max_amount <= 0:
        return {"ok": False, "prepared": False, "message": "Enter a budget greater than zero."}
    if type(quantity) is not int or quantity < 1 or quantity > 20:
        return {"ok": False, "prepared": False, "message": "Quantity must be from 1 to 20."}
    if type(different_models) is not int or different_models < 1 or different_models > 10:
        return {"ok": False, "prepared": False, "message": "Choose from 1 to 10 different shoe models."}
    if product_id and different_models > 1:
        return {"ok": False, "prepared": False,
                "message": "A specific product was selected together with a request for different models. Choose one product or remove the specific product selection."}
    try:
        products = filter_products(fetch_footwear_products(), query)
    except RuntimeError as error:
        return {"ok": False, "prepared": False, "message": str(error)}

    if product_id:
        products = [product for product in products if product.get("id") == product_id]
    available = [product for product in products
                 if str(product.get("availability", "IN_STOCK")).upper() in ("IN_STOCK", "AVAILABLE")
                 and int(product.get("availableQuantity", quantity) or 0) >= quantity]
    available = [product for product in available if str(product.get("currency", "USD")).upper() == "USD"]
    available.sort(key=lambda item: float(item.get("price", 0)))
    selected = []
    selected_total = 0.0
    for product in available:
        line_total = float(product.get("price", 0)) * quantity
        if selected_total + line_total <= max_amount:
            selected.append(product)
            selected_total += line_total
            if len(selected) == different_models:
                break
    if len(selected) < different_models:
        if not available:
            message = "No matching in-stock shoe was found. Try changing the search or quantity."
        else:
            cheapest_total = sum(float(product.get("price", 0)) * quantity
                                 for product in available[:different_models])
            message = (f"Could not find {different_models} different matching shoes within the ${max_amount:.2f} USD "
                       f"budget. The least expensive {min(different_models, len(available))} matching options total "
                       f"${cheapest_total:.2f} USD. Increase the budget or ask for fewer models.")
        return {"ok": False, "prepared": False, "message": message}

    # Select distinct, least-expensive matching models whose combined total fits the budget.
    selected_items = [{"product_id": product["id"], "quantity": quantity} for product in selected]
    approval_id = str(uuid.uuid4())
    PREPARED_PURCHASES[approval_id] = {
        "max_amount": round(max_amount, 2), "query": query, "quantity": quantity,
        "items": selected_items, "cart_id": cart_id,
    }
    selected_products = [{"id": product["id"], "name": product.get("name", "Footwear item"),
                          "description": product.get("description", ""),
                          "category": product.get("category", "Footwear"),
                          "price": float(product.get("price", 0)), "currency": product.get("currency", "USD"),
                          "quantity": quantity, "lineTotal": round(float(product.get("price", 0)) * quantity, 2),
                          "image": product_image_source(product, index)}
                         for index, product in enumerate(selected)]
    return {
        "ok": True, "prepared": True, "approvalId": approval_id,
        "budget": round(max_amount, 2), "quantity": quantity, "products": selected_products,
        "itemTotal": round(selected_total, 2),
        "message": "Merchant found the matching shoe model(s) within your budget. Review the complete selection and approve before it is added.",
    }


@shop.tool()
def start_shopping_session(approval_id: str) -> dict:
    """UI-only action: save the budget after the shopper submits the authorization form.

    This tool is private to the shop UI. The shopper must click its explicit accept button;
    it uses the selected product/budget prepared for that UI screen. The AI must not call it
    directly. The budget is simulated, not signed AP2 evidence.
    """
    global ACTIVE_SESSION_ID
    prepared = PREPARED_PURCHASES.get(approval_id)
    if not prepared:
        return {"ok": False, "message": "This purchase approval expired or was already used. Start the purchase again."}
    max_amount = prepared["max_amount"]
    prepared_items = prepared["items"]
    cart_id = prepared["cart_id"]
    session_id = str(uuid.uuid4())
    try:
        session = merchant_request("POST", "/api/merchant-sessions", {
            "sessionId": session_id,
            "maxAmount": round(max_amount, 2),
            "currency": "USD",
        })
    except RuntimeError as error:
        return {"ok": False, "message": str(error)}
    PREPARED_PURCHASES.pop(approval_id, None)
    ACTIVE_SESSION_ID = session_id
    SESSIONS[session_id] = session
    active_cart = None
    if cart_id and cart_id.strip():
        try:
            merchant_request("POST", f"/merchant-cart/{cart_id}/shopping-journey", {
                "journeyId": session["journeyId"],
                "mandateId": session["mandateId"],
            })
            active_cart = merchant_request("GET", f"/merchant-cart/{cart_id}")
        except RuntimeError as error:
            return {"ok": False, "session": session, "message":
                    f"The demo budget was recorded, but Merchant could not resume cart {cart_id}: {error}"}
    CARTS[session_id] = active_cart
    session["checkoutOperationId"] = None
    session["completed"] = False
    item_result = apply_items_to_demo_cart(prepared_items, session_id)
    return {"ok": item_result.get("ok", False), "session": session,
            "purchaseResult": item_result, "cart": current_cart(session_id),
            "message": (item_result.get("message") if item_result else
                        f"Started a simulated shopping session with a ${session['maxAmount']:.2f} USD limit. This is not AP2 authorization.")}


def cart_request_body(items: list[dict], session: dict | None = None) -> dict:
    payload = {
        "items": items,
        "customer": {
            "name": {"given_name": "Demo", "surname": "Shopper"},
            "email_address": "buyer@example.com",
        },
        "shipping_address": {
            "address_line_1": "1 Main St", "admin_area_2": "San Jose",
            "admin_area_1": "CA", "postal_code": "95131", "country_code": "US",
        },
    }
    if session:
        payload["journey_id"] = session["journeyId"]
        payload["mandate_id"] = session["mandateId"]
    return payload


def apply_items_to_demo_cart(items: list[dict], session_id: str) -> dict:
    """Submit one complete proposed cart so Guard evaluates the combined set atomically."""
    global PRODUCTS
    try:
        session_id, session = resolve_session(session_id)
    except RuntimeError as error:
        return {"ok": False, "message": str(error)}
    active_cart = CARTS.get(session_id)
    try:
        PRODUCTS = fetch_footwear_products()
    except RuntimeError as error:
        return {"message": str(error), "ok": False, "cart": current_cart(session_id)}
    product_by_id = {str(product.get("id")): product for product in PRODUCTS}
    current_items = {str(item.get("variant_id")): int(item.get("quantity", 0))
                     for item in (active_cart or {}).get("items", [])}
    names = []
    for proposed in items:
        product_id = str(proposed.get("product_id", ""))
        quantity = proposed.get("quantity", 0)
        if type(quantity) is not int or quantity < 1 or quantity > 20:
            return {"ok": False, "decision": "BLOCK", "message": "Quantity must be a whole number from 1 to 20."}
        product = product_by_id.get(product_id)
        if not product:
            return {"ok": False, "decision": "BLOCK", "message": f"Product {product_id} was not found."}
        current_items[product_id] = current_items.get(product_id, 0) + quantity
        names.append({"productId": product_id, "name": product.get("name", "Footwear item"),
                      "quantity": quantity})

    payload = cart_request_body([{"variant_id": item_id, "quantity": item_quantity}
                                 for item_id, item_quantity in current_items.items()],
                                session if not active_cart else None)
    try:
        if active_cart and active_cart.get("id"):
            updated = merchant_request("PUT", f"/merchant-cart/{active_cart['id']}", payload)
        else:
            updated = merchant_request("POST", "/merchant-cart", payload)
    except RuntimeError as error:
        return {"ok": False, "decision": "BLOCK" if "HTTP 409" in str(error) else None,
                "message": str(error), "cart": current_cart(session_id)}
    CARTS[session_id] = updated
    return {"ok": True, "decision": "ALLOW", "addedItems": names,
            "message": "Merchant saved the complete proposed set after Mandate Lens allowed the cart.",
            "cart": current_cart(session_id)}


@shop.tool(model=False)
def add_item_to_demo_cart(product_id: str, quantity: int = 1, session_id: str = "") -> dict:
    """Ask Merchant to add a catalog item and quantity to the active budgeted session.

    Call only after the shopper submits the shop UI budget approval form and the tool confirms the
    product (or selected it from the returned Merchant catalog). Use the exact catalog
    product ID, and pass the requested quantity in one call. Merchant submits the complete
    proposed cart to Mandate Lens/AgentGuard; the cart changes only if Guard allows it.
    Report success only when this tool returns ok=true and decision=ALLOW. If ok=false,
    report the returned reason and do not say the item was added. This does not approve
    checkout or make a payment.
    """
    if type(quantity) is not int or quantity < 1 or quantity > 20:
        return {"ok": False, "decision": "BLOCK",
                "message": "quantity must be a whole number from 1 to 20."}
    return apply_items_to_demo_cart([{"product_id": product_id, "quantity": quantity}], session_id)


@shop.tool(model=False)
def reset_demo_cart(session_id: str = "") -> dict:
    """Clear an open cart through Merchant; completed orders remain saved and read-only."""
    try:
        session_id, session = resolve_session(session_id, allow_completed=True)
    except RuntimeError as error:
        return {"ok": False, "message": str(error)}
    active_cart = CARTS.get(session_id)
    if session.get("completed") or (active_cart and active_cart.get("status") == "COMPLETED"):
        CARTS[session_id] = None
        session["completed"] = True
        return {"ok": True,
                "message": "Cleared the completed purchase from this shop view. The order and Pulse journey remain saved. Start a new budgeted shopping session before buying again.",
                "cart": current_cart(session_id)}
    if not active_cart or not active_cart.get("id"):
        return {"ok": True, "message": "The cart is already empty.", "cart": current_cart(session_id)}
    if session.get("checkoutOperationId"):
        try:
            merchant_request("POST", f"/merchant-cart/{active_cart['id']}/checkout-approval", {
                "operationId": session["checkoutOperationId"], "approved": False,
            })
        except RuntimeError as error:
            return {"ok": False, "message": str(error), "cart": current_cart(session_id)}
        session["checkoutOperationId"] = None
    try:
        CARTS[session_id] = merchant_request("PUT", f"/merchant-cart/{active_cart['id']}",
                                             cart_request_body([]))
    except RuntimeError as error:
        return {"ok": False, "message": str(error), "cart": current_cart(session_id)}
    return {"message": "Merchant cleared the cart; Mandate Lens saved the removal event.",
            "ok": True, "cart": current_cart(session_id)}


@shop.tool(model=False)
def preview_demo_checkout(session_id: str = "") -> dict:
    """Ask Merchant and AgentGuard to check the whole cart before the shopper approves checkout."""
    try:
        session_id, session = resolve_session(session_id)
    except RuntimeError as error:
        return {"ok": False, "message": str(error)}
    if session.get("completed"):
        return {"ok": False, "message": "This shopping journey is complete. Start a new session before checking out again."}
    cart = CARTS.get(session_id)
    if not cart or not cart.get("id") or not cart.get("items"):
        return {"ok": False, "message": "Add at least one item before checkout.", "cart": current_cart(session_id)}
    try:
        result = merchant_request("POST", f"/merchant-cart/{cart['id']}/checkout-preview", {})
    except RuntimeError as error:
        session["checkoutOperationId"] = None
        return {"ok": False, "decision": "BLOCK", "message": str(error),
                "session": session, "cart": current_cart(session_id)}
    decision = str(result.get("decision", "BLOCK")).upper()
    session["checkoutOperationId"] = result.get("operationId") if decision == "ALLOW" else None
    return {"ok": decision == "ALLOW", **result, "decision": decision,
            "session": session, "cart": current_cart(session_id),
            "message": ("Guard allowed this cart. No payment has happened. Review the decision details, then approve or decline."
                        if decision == "ALLOW" else
                        "Guard blocked this cart. Review the reasons below and change the cart before retrying.")}


@shop.tool(model=False)
def approve_demo_checkout(session_id: str = "") -> dict:
    """Record the shopper's explicit approval and complete the simulated demo payment."""
    global ACTIVE_SESSION_ID
    try:
        session_id, session = resolve_session(session_id)
    except RuntimeError as error:
        return {"ok": False, "message": str(error)}
    if session.get("completed"):
        return {"ok": False, "message": "This shopping journey is already complete."}
    operation_id = session.get("checkoutOperationId")
    cart = CARTS.get(session_id)
    if not operation_id or not cart or not cart.get("id"):
        return {"ok": False, "message": "Review checkout first, then approve the displayed cart."}
    try:
        result = merchant_request("POST", f"/merchant-cart/{cart['id']}/checkout-approval", {
            "operationId": operation_id, "approved": True,
        })
    except RuntimeError as error:
        return {"ok": False, "message": str(error), "session": session,
                "cart": current_cart(session_id)}
    if result.get("status") != "COMPLETED":
        return {"ok": False, "message": result.get("message", "Merchant did not complete the demo checkout."),
                "session": session, "cart": current_cart(session_id)}
    session["completed"] = True
    try:
        CARTS[session_id] = merchant_request("GET", f"/merchant-cart/{cart['id']}")
    except RuntimeError:
        # Approval is already recorded; preserve the local snapshot if the follow-up read fails.
        CARTS[session_id] = cart
    session["checkoutOperationId"] = None
    if ACTIVE_SESSION_ID == session_id:
        ACTIVE_SESSION_ID = None
    storefront_products = []
    try:
        products = fetch_footwear_products()
        images = preload_product_images(products)
        storefront_products = [{**product, "image": image}
                               for product, image in zip(products, images)]
    except RuntimeError:
        pass
    return {"ok": True, **result, "session": session, "purchaseCompleted": True,
            "storefrontProducts": storefront_products, "cart": current_cart(session_id),
            "message": "Purchase complete. This shopping session has ended. Browse the full Merchant catalog below."}


@shop.tool(model=False)
def decline_demo_checkout(session_id: str = "") -> dict:
    """Record that the shopper declined the reviewed checkout; no payment is made."""
    try:
        session_id, session = resolve_session(session_id)
    except RuntimeError as error:
        return {"ok": False, "message": str(error)}
    if session.get("completed"):
        return {"ok": False, "message": "This shopping journey is already complete."}
    operation_id = session.get("checkoutOperationId")
    cart = CARTS.get(session_id)
    if not operation_id or not cart or not cart.get("id"):
        return {"ok": False, "message": "Review checkout first before declining it."}
    try:
        result = merchant_request("POST", f"/merchant-cart/{cart['id']}/checkout-approval", {
            "operationId": operation_id, "approved": False,
        })
    except RuntimeError as error:
        return {"ok": False, "message": str(error), "session": session,
                "cart": current_cart(session_id)}
    session["checkoutOperationId"] = None
    return {"ok": True, **result, "session": session, "cart": current_cart(session_id)}


@shop.tool(model=False)
def get_footwear_products(query: str = "") -> dict:
    """Look up footwear in the live merchant catalog.

    Call this tool when the shopper asks to browse, list, compare, or find footwear such as
    running shoes, sneakers, boots, or sandals. Also call it during a purchase flow when the
    shopper has not named an exact catalog product. Use the returned product IDs for cart
    actions; never invent product IDs, prices, availability, or product names. Browsing this
    catalog alone does not start a shopping session or add anything to a cart.
    """
    global PRODUCTS
    try:
        PRODUCTS = fetch_footwear_products()
    except RuntimeError as error:
        return {"ok": False, "source": "merchant product API", "message": str(error), "products": []}
    matched = filter_products(PRODUCTS, query)
    return {"ok": True, "source": "merchant product API", "count": len(matched), "products": matched}


@shop.tool(model=False)
def return_to_shop_home() -> dict:
    """UI-only navigation after the completed purchase success screen."""
    global PRODUCTS, ACTIVE_SESSION_ID
    ACTIVE_SESSION_ID = None
    try:
        PRODUCTS = fetch_footwear_products()
        images = preload_product_images(PRODUCTS)
        storefront_products = [{**product, "image": image}
                               for product, image in zip(PRODUCTS, images)]
    except RuntimeError as error:
        return {"ok": False, "message": str(error), "returnedHome": False,
                "purchaseCompleted": True}
    return {"ok": True, "returnedHome": True, "purchaseCompleted": False,
            "prepared": False, "session": None, "storefrontProducts": storefront_products,
            "message": "Welcome to the StrideHub shop.",
            "cart": {"items": [], "total": 0, "currency": "USD"}}


@shop.ui()
def open_shoe_shop(query: str = "", max_amount: float | None = None,
                   cart_id: str = "", quantity: int = 1, purchase: bool = False,
                   product_id: str = "", different_models: int = 1) -> PrefabApp:
    """Browse the catalog, or guide a purchase through budget, search, and approval in order.

    If a purchase request has no budget, call this with purchase=True and no max_amount.
    It shows the budget form before fetching products. Once entered, the UI searches Merchant
    and shows one or more distinct affordable shoe models. Set different_models to the number
    of distinct models requested. Quantity is the number of each selected model.
    """
    global PRODUCTS
    purchase = purchase or bool(product_id) or max_amount is not None
    if purchase and max_amount is not None:
        initial_result = prepare_purchase_item(max_amount, query, quantity, product_id, cart_id, different_models)
    else:
        initial_result = {
            "ok": True, "prepared": False, "session": None,
            "message": ("Enter a total budget first. Merchant will search after you submit it."
                        if purchase else "Browse the live catalog. No budget, journey, or cart is created."),
            "cart": {"items": [], "total": 0, "currency": "USD"},
        }

    browse_products: list[dict] = []
    browse_images: list[str] = []
    catalog_error = None
    if not purchase:
        try:
            PRODUCTS = filter_products(fetch_footwear_products(), query)
            browse_products = PRODUCTS
            browse_images = preload_product_images(browse_products)
        except RuntimeError as error:
            catalog_error = str(error)

    with Column(gap=5, css_class="p-5 min-h-screen") as view:
        with If("!result.purchaseCompleted"):
            with Row(justify="between", align="center"):
                with Column(gap=1):
                    Small("AI SHOPPING · LOCAL DEMO", bold=True, css_class="tracking-widest text-muted-foreground")
                    Heading("StrideHub running shoes", level=1)
                Badge("LOCAL MERCHANT DEMO", variant="warning")

        if purchase:
            with If("!result.returnedHome && !result.purchaseCompleted"):
                Text("First set your total budget. Then Merchant will search and show the matching shoe selection for your approval.",
                     css_class="text-sm text-muted-foreground")
            with If("!result.prepared && !result.session && !result.returnedHome && !result.purchaseCompleted"):
                with Card():
                    with CardHeader():
                        Heading("Step 1 · Set your total budget", level=2)
                        Text("No product search or shopping journey starts until you submit this amount.")
                    with CardContent():
                        with Form(on_submit=CallTool(
                                prepare_purchase_item,
                                arguments={"max_amount": "{{ max_amount }}", "query": query,
                                           "quantity": quantity, "product_id": product_id,
                                           "cart_id": cart_id, "different_models": different_models},
                                onSuccess=SetState("result", RESULT))):
                            Text("Maximum budget (USD)")
                            Input(name="max_amount", value=f"{max_amount:.2f}" if max_amount else "",
                                  input_type="number", min=0.01, step=0.01, required=True,
                                  placeholder="What is your total budget?")
                            Button("Continue to find shoes", variant="success", buttonType="submit")
                            Text(Rx("result.message"), css_class="text-sm text-muted-foreground")
                            Text("Demo only: this is a simulated budget, not a signed AP2 authorization.",
                                 css_class="text-xs text-muted-foreground")

            with If("result.prepared && !result.session"):
                with Card():
                    with CardHeader():
                        Heading("Step 2 · Review selected shoes", level=2)
                        Text("We chose the least expensive distinct matching in-stock models that fit your budget.")
                    with CardContent():
                        with Column(gap=4):
                            with ForEach("result.products") as product:
                                with Row(gap=4, align="center", css_class="border-b py-3"):
                                    Image(src=product.image, alt=product.name, width="180px", height="130px")
                                    with Column(gap=2):
                                        Heading(product.name, level=3)
                                        Text(product.description)
                                        Text(f"Quantity: {product.quantity}")
                                        Text(f"Unit price: ${product.price} USD")
                                        Text(f"Line total: ${product.lineTotal} USD")
                            Separator()
                            Text(f"Selected total: ${Rx('result.itemTotal')} USD")
                            Text(f"Your budget: ${Rx('result.budget')} USD")
                            Button("Approve selection and add to cart", variant="success", onClick=CallTool(
                                start_shopping_session,
                                arguments={"approval_id": "{{ result.approvalId }}"},
                                onSuccess=SetState("result", RESULT)))
                            Button("Decline and return to the shop", variant="outline", onClick=SetState(
                                "result", {"ok": False, "prepared": False, "session": None,
                                            "message": "Purchase declined. No journey or cart was created.",
                                            "cart": {"items": [], "total": 0, "currency": "USD"}}))

            with If("result.session && !result.purchaseCompleted"):
                with Card():
                    with CardHeader():
                        Heading("Merchant cart", level=2)
                    with CardContent():
                        with Column(gap=3):
                            with ForEach("result.cart.items") as line:
                                with Row(justify="between", css_class="border-b py-2"):
                                    Text(line.name)
                                    Text(line.quantity)
                                    Text(line.line_total)
                            Separator()
                            with Row(justify="between", align="center"):
                                Text("Cart total", css_class="font-semibold")
                                Heading(Rx("result.cart.total"), level=3)
                                Text(Rx("result.cart.currency"))
                            Text(Rx("result.message"), css_class="text-sm text-muted-foreground")
                with If("result.cart.items.length > 0"):
                    with Card():
                        with CardHeader():
                            Heading("Step 3 · Final cart check", level=2)
                            Text("This asks Guard to check the latest full cart and budget before you approve payment.")
                        with CardContent():
                            with Column(gap=4):
                                with If("!result.guardResult"):
                                    Button("Check final cart with Guard", variant="outline", onClick=CallTool(
                                        preview_demo_checkout, onSuccess=SetState("result", RESULT)))
                                with If("result.operationId"):
                                    with Card(css_class="border-emerald-300 bg-emerald-50 text-emerald-950"):
                                        with CardHeader():
                                            Badge("GUARD ALLOWED", variant="success")
                                            Heading("Checkout approved by Guard", level=3)
                                            Text("Guard allowed the checkout. Review the result below before approving payment.")
                                with If("result.guardResult && !result.operationId"):
                                    with Card(css_class="border-red-300 bg-red-50 text-red-950"):
                                        with CardHeader():
                                            Badge("GUARD BLOCKED", variant="destructive")
                                            Heading("Checkout needs attention", level=3)
                                            Text("Guard blocked this cart. Review its reasons and change the cart before trying again.")
                                with If("result.guardResult"):
                                    with Card():
                                        with CardHeader():
                                            Heading("Mandate Lens · AgentGuard details", level=3)
                                        with CardContent():
                                            with Column(gap=2):
                                                Text(f"Decision: {Rx('result.decision')}")
                                                Text(f"Operation ID: {Rx('result.guardResult.operationId')}")
                                                Text(f"Decision ID: {Rx('result.guardResult.decisionId')}")
                                                Text(f"Policy version: {Rx('result.guardResult.policyVersion')}")
                                                Text(f"Evaluated at: {Rx('result.guardResult.evaluatedAt')}")
                                                Text("Reasons")
                                                with If("result.guardResult.reasons.length > 0"):
                                                    with ForEach("result.guardResult.reasons") as reason:
                                                        Text(f"{reason.code}: {reason.message}")
                                                with If("result.guardResult.reasons.length == 0"):
                                                    Text("No blocking reasons were returned.")
                                                Text("Rule results")
                                                with ForEach("result.guardResult.ruleResults") as rule:
                                                    Text(f"{rule.ruleId} · {rule.result}: {rule.message}")
                                Button("Approve & pay (demo)", variant="success",
                                       disabled=Rx("!result.operationId"), onClick=CallTool(
                                           approve_demo_checkout, onSuccess=SetState("result", RESULT)))
                                Button("Decline checkout", variant="outline",
                                       disabled=Rx("!result.operationId"), onClick=CallTool(
                                           decline_demo_checkout, onSuccess=SetState("result", RESULT)))

            with If("result.purchaseCompleted && !result.returnedHome"):
                with Column(gap=5, align="center", justify="center",
                            css_class="min-h-[75vh] w-full text-center animate-in fade-in zoom-in duration-700"):
                    Text("✓", css_class="text-7xl font-bold text-emerald-500 animate-bounce")
                    Badge("PAYMENT SUCCESSFUL", variant="success")
                    Heading("Your demo purchase is complete!", level=1)
                    Text(Rx("result.message"), css_class="text-muted-foreground")
                    Text("Mandate Lens recorded the successful journey. No real money was moved.",
                         css_class="text-muted-foreground")
                    Text(f"Order: {Rx('result.orderId')}")
                    Button("Go to home page", variant="success", size="lg", onClick=CallTool(
                        return_to_shop_home, onSuccess=SetState("result", RESULT)))

            with If("result.returnedHome"):
                Heading("StrideHub footwear", level=1)
                Text("Choose a shoe to start a new shopping session.",
                     css_class="text-sm text-muted-foreground")
                with Grid(columns=[1, 1, 1], gap=4):
                    with ForEach("result.storefrontProducts") as product:
                        with Card():
                            Image(src=product.image, alt=product.name, width="100%", height="150px")
                            with CardHeader():
                                Small(product.category, bold=True)
                                Heading(product.name, level=3)
                            with CardContent():
                                Text(product.description)
                                Text(f"{product.price} {product['currency']}")

        else:
            Text("Browse the Merchant catalog. Browsing does not start a shopping journey or create a budget.",
                 css_class="text-sm text-muted-foreground")
            if catalog_error:
                Text(catalog_error)
            elif not browse_products:
                Text("No footwear matched that search. Try a broader product request.")
            with Grid(columns=[1, 1, 1], gap=4):
                for index, product in enumerate(browse_products):
                    with Card():
                        Image(src=browse_images[index], alt=f"{product.get('name', 'Footwear')} product image",
                              width="100%", height="150px")
                        with CardHeader():
                            Small(str(product.get("category", "Footwear")).replace("_", " ").upper(), bold=True)
                            Heading(str(product.get("name", "Footwear")), level=3)
                        with CardContent():
                            Text(str(product.get("description", "")))
                            Text(f"{float(product.get('price', 0)):.2f} {product.get('currency', 'USD')}")

    return PrefabApp(view=view, state={"result": initial_result})


