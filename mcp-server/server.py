def current_cart(session_id: str | None = None) -> dict:
    session_id = session_id or ACTIVE_SESSION_ID
    session = SESSIONS.get(session_id) if session_id else None
    active_cart = CARTS.get(session_id) if session_id else None
    if not active_cart:
        return {"items": [], "total": 0, "currency": "USD",
                "budget": session.get("maxAmount") if session and not session.get("completed") else None,
                "status": "COMPLETED" if session and session.get("completed") else "EMPTY"}

    products_by_id = {product.get("id"): product for product in PRODUCTS}
    lines = []
    for item in active_cart.get("items", []):
        product = products_by_id.get(item.get("variant_id"), {})
        line_total = float((item.get("item_total") or {}).get("value") or 0)
        lines.append({**product, "id": item.get("variant_id"),
                      "name": item.get("name") or product.get("name", "Footwear item"),
                      "quantity": item.get("quantity", 0), "line_total": line_total})
    total = float(((active_cart.get("totals") or {}).get("total") or {}).get("value") or 0)
    return {"items": lines, "total": total,
            "currency": ((active_cart.get("totals") or {}).get("total") or {}).get("currency_code", "USD"),
            "budget": session.get("maxAmount") if session and not session.get("completed") else None,
            "status": "COMPLETED" if session and session.get("completed")
            else active_cart.get("status", "ACTIVE")}


def resolve_session(session_id: str | None = None, allow_completed: bool = False) -> tuple[str, dict]:
    resolved_id = session_id or ACTIVE_SESSION_ID
    session = SESSIONS.get(resolved_id) if resolved_id else None
    if not session:
        raise RuntimeError("No shopping session is active. Browsing is available now; before adding items, ask the shopper for a budget and start a shopping session.")
    if session.get("completed") and not allow_completed:
        raise RuntimeError("This shopping journey is complete and its cart is read-only. Start a new shopping session before adding items again.")
    return resolved_id, session


def merchant_request(method: str, path: str, payload: dict | None = None) -> dict:
    body = json.dumps(payload).encode("utf-8") if payload is not None else None
    request = Request(f"{MERCHANT_API_BASE_URL}{path}", data=body, method=method,
                      headers={"Accept": "application/json", "Content-Type": "application/json"})
    try:
        with urlopen(request, timeout=10) as response:
            return json.loads(response.read().decode("utf-8"))
    except HTTPError as error:
        detail = error.read().decode("utf-8", errors="replace")
        try:
            problem = json.loads(detail)
            detail = problem.get("detail") or problem.get("message") or detail
        except json.JSONDecodeError:
            pass
        raise RuntimeError(f"Merchant API returned HTTP {error.code}: {detail}") from error
    except (URLError, TimeoutError, json.JSONDecodeError) as error:
        raise RuntimeError(
            f"Could not reach Merchant API at {MERCHANT_API_BASE_URL}. Start the merchant API and try again."
        ) from error


def fetch_footwear_products() -> list[dict]:
    """Fetch current footwear records from the merchant's product API."""
    request = Request(
        f"{MERCHANT_API_BASE_URL}/api/products",
        headers={"Accept": "application/json"},
    )
    try:
        with urlopen(request, timeout=5) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except HTTPError as error:
        raise RuntimeError(f"Merchant product API returned HTTP {error.code}.") from error
    except (URLError, TimeoutError, json.JSONDecodeError) as error:
        raise RuntimeError(
            f"Could not load products from {MERCHANT_API_BASE_URL}. Start the merchant API and try again."
        ) from error

    if not isinstance(payload, list):
        raise RuntimeError("Merchant product API returned an unexpected response.")

    products = [
        product for product in payload
        if isinstance(product, dict)
        and any(token in str(product.get("category", "")).upper()
                for token in ("SHOE", "FOOTWEAR", "SNEAKER", "BOOT", "SANDAL"))
    ]
    products.sort(key=lambda product: str(product.get("name", "")).casefold())
    return products


def filter_products(products: list[dict], query: str) -> list[dict]:
    terms = [term.casefold() for term in query.split() if term.strip()]
    if not terms:
        return products
    return [product for product in products if all(
        term in " ".join(str(product.get(key, "")).replace("_", " ")
                          for key in ("name", "description", "category")).casefold()
        for term in terms
    )]


