                    with If("result.paymentMethodType == 'paypal'"):
                        Heading("Your PayPal Sandbox purchase is complete!", level=1)
                    with If("result.paymentMethodType != 'paypal'"):
                        Heading("Your demo purchase is complete!", level=1)
                    Text(Rx("result.message"), css_class="text-muted-foreground")
